//! The table of supported receivers. Adding a receiver that speaks an existing protocol is one
//! line here; the udev rule is generated from this table (`whiskerd --udev-rules`).

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Protocol {
    /// Feature report 0x0C status query (see `drivers::compx`).
    Compx,
    /// Pushed 0x54 events plus slot query on interface 3 (see `drivers::keychron`).
    KeychronLink,
}

#[derive(Debug, PartialEq, Eq)]
pub struct Receiver {
    pub vid: u16,
    pub pid: u16,
    /// USB interface number of the vendor collection.
    pub iface: u8,
    pub protocol: Protocol,
    /// Shown until the mouse identifies itself.
    pub label: &'static str,
    /// true = tested on real hardware by this project; false = reported by others.
    pub verified: bool,
}

const fn rx(
    vid: u16,
    pid: u16,
    protocol: Protocol,
    label: &'static str,
    verified: bool,
) -> Receiver {
    Receiver {
        vid,
        pid,
        iface: 1,
        protocol,
        label,
        verified,
    }
}

pub const RECEIVERS: &[Receiver] = &[
    rx(0x248a, 0x5b2f, Protocol::Compx, "2.4 GHz mouse", true),
    rx(0x248a, 0x5b2e, Protocol::Compx, "Wired mouse", false),
    rx(0x331a, 0x5024, Protocol::Compx, "Wired mouse", false),
    rx(
        0x3434,
        0xd031,
        Protocol::KeychronLink,
        "Keychron mouse",
        true,
    ),
    rx(
        0x3434,
        0xd030,
        Protocol::KeychronLink,
        "Keychron mouse",
        false,
    ),
];

pub fn find(vid: u16, pid: u16, iface: u8) -> Option<&'static Receiver> {
    RECEIVERS
        .iter()
        .find(|r| r.vid == vid && r.pid == pid && r.iface == iface)
}

/// udev rule giving the logged-in user access to every supported receiver's hidraw nodes.
pub fn udev_rules() -> String {
    let mut s = String::from(
        "# Generated by `whiskerd --udev-rules`. Grants the active local user access to the\n\
         # hidraw nodes of supported wireless mouse receivers (read battery status only).\n",
    );
    let mut seen: Vec<(u16, u16)> = Vec::new();
    for r in RECEIVERS {
        if seen.contains(&(r.vid, r.pid)) {
            continue;
        }
        seen.push((r.vid, r.pid));
        s += &format!(
            "SUBSYSTEM==\"hidraw\", ATTRS{{idVendor}}==\"{:04x}\", ATTRS{{idProduct}}==\"{:04x}\", TAG+=\"uaccess\"\n",
            r.vid, r.pid
        );
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn finds_by_vid_pid_iface() {
        assert_eq!(find(0x248a, 0x5b2f, 1).unwrap().protocol, Protocol::Compx);
        assert_eq!(
            find(0x3434, 0xd031, 1).unwrap().protocol,
            Protocol::KeychronLink
        );
        assert_eq!(find(0x3434, 0xd031, 0), None);
        assert_eq!(find(0xfffe, 0x0011, 1), None);
    }

    #[test]
    fn udev_rules_cover_table() {
        let rules = udev_rules();
        assert!(rules.contains(
            "SUBSYSTEM==\"hidraw\", ATTRS{idVendor}==\"248a\", ATTRS{idProduct}==\"5b2f\", TAG+=\"uaccess\"\n"
        ));
        assert!(rules.contains("ATTRS{idProduct}==\"d031\""));
        let lines = rules.lines().filter(|l| l.starts_with("SUBSYSTEM")).count();
        assert_eq!(lines, RECEIVERS.len());
    }
}
